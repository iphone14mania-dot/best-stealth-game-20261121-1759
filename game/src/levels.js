// Count the treasures, guards and other facts of a level for the HUD
// and the level-select screen.
export function levelFacts(level) {
  let treasures = 0;
  for (const row of level.map) for (const ch of row) if (ch === 'T') treasures += 1;
  return { treasures, guards: level.guards.length };
}

// Walk the map once and pull out the tiles the world needs as objects:
// the player start, the gem, the exit and every treasure. The tiles
// themselves stay as floor under those objects.
export function parseMap(level) {
  const tiles = [];
  let player = { x: 2, y: 2 };
  let gem = null;
  let exit = null;
  const treasures = [];
  for (let y = 0; y < level.map.length; y += 1) {
    const row = [];
    for (let x = 0; x < level.map[y].length; x += 1) {
      const ch = level.map[y][x];
      if (ch === 'P') { player = { x: x + 0.5, y: y + 0.5 }; row.push('.'); }
      else if (ch === 'X') { gem = { x: x + 0.5, y: y + 0.5 }; row.push('.'); }
      else if (ch === 'E') { exit = { x: x + 0.5, y: y + 0.5 }; row.push('.'); }
      else if (ch === 'T') { treasures.push({ x: x + 0.5, y: y + 0.5, taken: false }); row.push('.'); }
      else row.push(ch);
    }
    tiles.push(row);
  }
  return { tiles, player, gem, exit, treasures };
}
